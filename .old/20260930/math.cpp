#include "math.h"

// Math
int sum(int a, int b)
{
    return a + b;
}

int subtract(int a, int b)
{
    return a - b;
}

int multiply(int a, int b)
{
    return a * b;
}

double divide(double a, double b)
{
    return a / b;
}

// Comp
bool max(int a, int b)
{
    return a > b;
}

bool min(int a, int b)
{
    return a < b;
}

bool equal(int a, int b)
{
    return a == b;
}